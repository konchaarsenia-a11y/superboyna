#!/usr/bin/env node
/** Собирает fast/seed-inline.js из fast/data/*.json — ноль сетевых запросов на старте */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.join(__dirname, "..", "data");
const OUT = path.join(__dirname, "..", "seed-inline.js");

const DAY_FILE = {
  Понедельник: "clients-mon.json",
  Вторник: "clients-tue.json",
  Среда: "clients-wed.json",
  Четверг: "clients-thu.json",
  Пятница: "clients-fri.json",
  Суббота: "clients-sat.json",
  Воскресенье: "clients-sun.json",
  "Будущая неделя": "clients-future.json"
};

function readPayload(file) {
  try {
    const j = JSON.parse(fs.readFileSync(path.join(DATA, file), "utf8"));
    if (j && j.payload && j.payload.status === "success") return j.payload;
  } catch (e) {}
  return null;
}

const clients = {};
for (const [day, file] of Object.entries(DAY_FILE)) {
  const p = readPayload(file);
  if (p) clients[day] = p;
}
const weekDayCounts = readPayload("weekDayCounts.json");

const snap = { weekDayCounts, clients, builtAt: new Date().toISOString() };
const body =
  "/* auto-generated by build-seed-inline.mjs — do not edit */\n" +
  "window.__BOINYA_FAST_INLINE__ = " +
  JSON.stringify(snap) +
  ";\n";

fs.writeFileSync(OUT, body);
console.log("wrote", OUT, Buffer.byteLength(body), "bytes", "days=", Object.keys(clients).length);
